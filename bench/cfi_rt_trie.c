// Runtime support for the 'trie' CFI check variant.
// Compiled to bitcode and linked with the instrumented program AFTER the
// pass has run (so the pass does not instrument/analyse this code).
//
// One trie per function type. The allowed targets of a type are grouped in
// REGIONS: a region is a run of targets whose addresses are less than 2^24
// (16 MiB) apart. Typically a type has one region (all targets are in the
// program's own text), but targets can also be functions of a shared library
// (e.g. libc functions whose address the program takes), which live in a
// different mapping, far from the program, so those get a region of their own.
//
// Inside a region the keys are offsets from the lowest target of the region,
// split in three 8-bit levels:
//
//   off = p - base
//   l1[off >> 16]  ->  table of 256 leaf pointers
//   l2[(off >> 8) & 255]  ->  leaf: a 256-bit bitmap
//   bit (off & 255) of the leaf is set  <=>  p is an allowed target
//
// A lookup in the first region is at most 3 dependent loads and no loop.
// The region with the most targets is stored first, so that is the fast
// path; the other regions are searched by an out-of-line slow path.
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>

#define CFI_MAX_RANGE ((uintptr_t)1 << 24)

typedef struct cfi_region {
  uintptr_t base;       // lowest allowed target of the region
  uintptr_t range;      // highest - lowest + 1 (0 = empty region)
  uint64_t **l1[256];   // l1[off >> 16] -> 256 leaf pointers (or NULL)
} cfi_region;

typedef struct cfi_trie {
  unsigned nreg;        // number of regions, at least 1
  cfi_region reg[1];    // really nreg elements; reg[0] is the largest
} cfi_trie;

static void *xcalloc(size_t n, size_t sz) {
  void *p = calloc(n, sz);
  if (!p) {
    fputs("cfi: out of memory while building the trie\n", stderr);
    abort();
  }
  return p;
}

static int cmp_addr(const void *a, const void *b) {
  uintptr_t x = *(const uintptr_t *)a, y = *(const uintptr_t *)b;
  return (x > y) - (x < y);
}

static void region_insert(cfi_region *r, uintptr_t addr) {
  uintptr_t off = addr - r->base;
  uint64_t ***l1 = &r->l1[off >> 16];
  if (!*l1) *l1 = xcalloc(256, sizeof(uint64_t *));
  uint64_t **l2 = &(*l1)[(off >> 8) & 0xff];
  if (!*l2) *l2 = xcalloc(4, sizeof(uint64_t));
  unsigned bit = off & 0xff;
  (*l2)[bit >> 6] |= (uint64_t)1 << (bit & 63);
}

// Called once per target table by the constructor generated by the pass.
// Addresses are only known at load time (PIE/ASLR), so the trie is built here.
void *__cfi_trie_build(const uintptr_t *tab, unsigned n) {
  uintptr_t *s = xcalloc(n ? n : 1, sizeof *s);
  for (unsigned i = 0; i < n; i++) s[i] = tab[i];
  qsort(s, n, sizeof *s, cmp_addr);

  // split the sorted targets in regions: a new region starts when a target is
  // 2^24 or more above the first target of the current region
  unsigned nreg = 0;
  unsigned *first = xcalloc(n ? n : 1, sizeof *first);
  unsigned *count = xcalloc(n ? n : 1, sizeof *count);
  for (unsigned i = 0; i < n; i++) {
    if (nreg == 0 || s[i] - s[first[nreg - 1]] >= CFI_MAX_RANGE) {
      first[nreg] = i;
      nreg++;
    }
    count[nreg - 1]++;
  }

  unsigned alloc = nreg ? nreg : 1;
  cfi_trie *t = xcalloc(1, sizeof *t + (alloc - 1) * sizeof(cfi_region));
  t->nreg = alloc;
  for (unsigned r = 0; r < nreg; r++) {
    unsigned lo = first[r], hi = first[r] + count[r] - 1;
    t->reg[r].base = s[lo];
    t->reg[r].range = s[hi] - s[lo] + 1;
    for (unsigned i = lo; i <= hi; i++) region_insert(&t->reg[r], s[i]);
  }

  // the region with the most targets goes first (fast path)
  unsigned big = 0;
  for (unsigned r = 1; r < nreg; r++)
    if (count[r] > count[big]) big = r;
  if (big != 0) {
    cfi_region tmp = t->reg[0];
    t->reg[0] = t->reg[big];
    t->reg[big] = tmp;
  }
  free(s);
  free(first);
  free(count);
  return t;
}

static inline int region_lookup(const cfi_region *r, uintptr_t off) {
  uint64_t *const *l2 = r->l1[off >> 16];
  if (!l2) return 0;
  const uint64_t *leaf = l2[(off >> 8) & 0xff];
  if (!leaf) return 0;
  unsigned bit = off & 0xff;
  return (int)((leaf[bit >> 6] >> (bit & 63)) & 1);
}

// Targets that are not in the first region (rare: e.g. shared library
// functions). Kept out of line so the inlined fast path stays small.
__attribute__((noinline))
static int cfi_check_slow(const cfi_trie *t, uintptr_t p) {
  for (unsigned i = 1; i < t->nreg; i++) {
    uintptr_t off = p - t->reg[i].base;   // below base: wraps to a huge value
    if (off < t->reg[i].range) return region_lookup(&t->reg[i], off);
  }
  return 0;
}

// Returns 1 if p is an allowed target, 0 otherwise.
// always_inline: inlined at every call site by the final -O2 compile, so we
// measure the check itself and not the cost of a function call.
__attribute__((always_inline))
int __cfi_check_trie(const cfi_trie *t, uintptr_t p) {
  uintptr_t off = p - t->reg[0].base;     // below base: wraps to a huge value
  if (off < t->reg[0].range) return region_lookup(&t->reg[0], off);
  return t->nreg > 1 ? cfi_check_slow(t, p) : 0;
}
