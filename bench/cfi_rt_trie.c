// Runtime support for the 'trie' CFI check variant.
// Compiled to bitcode and linked with the instrumented program AFTER the
// pass has run (so the pass does not instrument/analyse this code).
//
// One trie per function type. Keys are offsets from the lowest allowed
// target of that type, split in three 8-bit levels (offsets < 2^24 = 16 MiB):
//
//   off = p - base
//   l1[off >> 16]  ->  table of 256 leaf pointers
//   l2[(off >> 8) & 255]  ->  leaf: a 256-bit bitmap
//   bit (off & 255) of the leaf is set  <=>  p is an allowed target
//
// A lookup is at most 3 dependent loads and no loop.
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>

#define CFI_MAX_RANGE ((uintptr_t)1 << 24)

typedef struct cfi_trie {
  uintptr_t base;       // lowest allowed target
  uintptr_t range;      // highest - lowest + 1
  uint64_t **l1[256];   // l1[off >> 16] -> 256 leaf pointers (or NULL)
} cfi_trie;

static void *xcalloc(size_t n, size_t sz) {
  void *p = calloc(n, sz);
  if (!p) {
    fputs("cfi: out of memory while building the trie\n", stderr);
    abort();
  }
  return p;
}

// Called once per target table by the constructor generated by the pass.
// Addresses are only known at load time (PIE/ASLR), so the trie is built here.
void *__cfi_trie_build(const uintptr_t *tab, unsigned n) {
  uintptr_t lo = tab[0], hi = tab[0];
  for (unsigned i = 1; i < n; i++) {
    if (tab[i] < lo) lo = tab[i];
    if (tab[i] > hi) hi = tab[i];
  }
  if (hi - lo >= CFI_MAX_RANGE) {
    fputs("cfi: targets span more than 16 MiB, trie cannot index them\n", stderr);
    abort();
  }
  cfi_trie *t = xcalloc(1, sizeof *t);
  t->base = lo;
  t->range = hi - lo + 1;
  for (unsigned i = 0; i < n; i++) {
    uintptr_t off = tab[i] - lo;
    uint64_t ***l1 = &t->l1[off >> 16];
    if (!*l1) *l1 = xcalloc(256, sizeof(uint64_t *));
    uint64_t **l2 = &(*l1)[(off >> 8) & 0xff];
    if (!*l2) *l2 = xcalloc(4, sizeof(uint64_t));
    unsigned bit = off & 0xff;
    (*l2)[bit >> 6] |= (uint64_t)1 << (bit & 63);
  }
  return t;
}

// Returns 1 if p is an allowed target, 0 otherwise.
// always_inline: inlined at every call site by the final -O2 compile, so we
// measure the check itself and not the cost of a function call.
__attribute__((always_inline))
int __cfi_check_trie(const cfi_trie *t, uintptr_t p) {
  uintptr_t off = p - t->base;       // below base: wraps around to a huge value
  if (off >= t->range) return 0;
  uint64_t *const *l2 = t->l1[off >> 16];
  if (!l2) return 0;
  const uint64_t *leaf = l2[(off >> 8) & 0xff];
  if (!leaf) return 0;
  unsigned bit = off & 0xff;
  return (int)((leaf[bit >> 6] >> (bit & 63)) & 1);
}
